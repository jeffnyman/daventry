    /// <summary>Expands a packed palette with <paramref name="fromBits"/> per component to 8-bit colours. Mirrors GfxMgr::initPalette.</summary>
    public static void Init(Span<Rgb> destination, ReadOnlySpan<byte> data, int colorCount = 16, int fromBits = 6, int toBits = 8)
    {
        int srcMax = (1 << fromBits) - 1;
        int destMax = (1 << toBits) - 1;
        for (int i = 0; i < colorCount; i++)
        {
            destination[i] = new Rgb(
                (byte)(data[i * 3] * destMax / srcMax),
                (byte)(data[i * 3 + 1] * destMax / srcMax),
                (byte)(data[i * 3 + 2] * destMax / srcMax));
        }
    }

    /// <summary>Converts a Macintosh CLUT to 8-bit colours with a gamma adjustment from 1.8 to 2.2. Mirrors GfxMgr::initPaletteCLUT.</summary>
    public static void InitClut(Span<Rgb> destination, ReadOnlySpan<ushort> clut, int colorCount = 16)
    {
        for (int i = 0; i < colorCount; i++)
        {
            destination[i] = new Rgb(Component(clut[i * 3]), Component(clut[i * 3 + 1]), Component(clut[i * 3 + 2]));
        }

        static byte Component(ushort value)
        {
            byte component = (byte)(value >> 8);
            return (byte)(255 * Math.Pow(component / 255.0f, 0.8181f));
        }
    }
