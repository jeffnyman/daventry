"""Converts ScummVM's engines/sci/sound/drivers/map-mt32-to-gm.h into MapMt32ToGm.g.cs.

The header holds the tables the General MIDI driver uses to play MT-32 music: the MT-32 preset
timbres, the rhythm timbres, the rhythm key map and the memory timbres of Sierra's patches, each
with the General MIDI instrument or rhythm key that stands in for it.

    python tools/PortTables/sci_mt32_to_gm.py [path/to/scummvm] [path/to/daventry]
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCUMMVM = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2] / "scummvm"
DAVENTRY = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE.parents[1]

SOURCE = SCUMMVM / "engines" / "sci" / "sound" / "drivers" / "map-mt32-to-gm.h"
OUTPUT = DAVENTRY / "src" / "Daventry.Sci" / "Sound" / "Drivers" / "MapMt32ToGm.g.cs"

CONSTANTS = {"MIDI_UNMAPPED": 0xFF, "MIDI_MAPPED_TO_RHYTHM": 0xFE}
ENTRY = re.compile(r'\{\s*"((?:[^"\\]|\\.)*)"\s*,\s*([A-Z_0-9]+)\s*,\s*([A-Z_0-9]+)\s*\}')


def value(token):
    return CONSTANTS[token] if token in CONSTANTS else int(token, 0)


def block(text, declaration):
    start = text.index(declaration)
    return text[text.index("{", start) + 1:text.index("};", start)]


def strip_comments(body):
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    return re.sub(r"//[^\n]*", "", body)


def maps(text, name):
    body = strip_comments(block(text, f"static const Mt32ToGmMap {name}[]"))
    return [(n, value(i), value(k)) for n, i, k in ENTRY.findall(body)]


def keymap(text, name):
    body = strip_comments(block(text, f"static const uint8 {name}[]"))
    return [value(t.strip()) for t in body.split(",") if t.strip()]


def emit_maps(name, entries):
    lines = [f"    public static readonly Mt32ToGmMap[] {name} =", "    ["]
    for n, instr, key in entries:
        escaped = n.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'        new("{escaped}", 0x{instr:02X}, 0x{key:02X}),')
    lines.append("    ];")
    return lines


def main():
    text = SOURCE.read_text(encoding="utf-8")
    preset = maps(text, "Mt32PresetTimbreMaps")
    rhythm = maps(text, "Mt32RhythmTimbreMaps")
    memory = maps(text, "Mt32MemoryTimbreMaps")
    keys = keymap(text, "Mt32PresetRhythmKeymap")
    assert len(preset) == 128 and len(keys) == 128, (len(preset), len(keys))

    out = [
        "// <auto-generated>",
        "// Generated by tools/PortTables/sci_mt32_to_gm.py from ScummVM's",
        "// engines/sci/sound/drivers/map-mt32-to-gm.h. Do not edit.",
        "// </auto-generated>",
        "",
        "namespace Daventry.Sci.Sound;",
        "",
        "/// <summary>The General MIDI stand-ins for MT-32 timbres. Port of map-mt32-to-gm.h.</summary>",
        "internal static class MapMt32ToGm",
        "{",
        "    /// <summary>Patch not mapped.</summary>",
        "    public const byte Unmapped = 0xFF;",
        "",
        "    /// <summary>Patch mapped to a rhythm key.</summary>",
        "    public const byte MappedToRhythm = 0xFE;",
        "",
    ]
    out += emit_maps("PresetTimbreMaps", preset) + [""]
    out += emit_maps("RhythmTimbreMaps", rhythm) + [""]
    out.append("    public static readonly byte[] PresetRhythmKeymap =")
    out.append("    [")
    for i in range(0, 128, 16):
        out.append("        " + " ".join(f"0x{k:02X}," for k in keys[i:i + 16]))
    out.append("    ];")
    out.append("")
    out += emit_maps("MemoryTimbreMaps", memory)
    out.append("}")
    out.append("")
    out.append("/// <summary>An MT-32 timbre by name and the General MIDI instrument or rhythm key that replaces it.</summary>")
    out.append("internal readonly record struct Mt32ToGmMap(string Name, byte GmInstr, byte GmRhythmKey);")
    OUTPUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{OUTPUT}: {len(preset)} preset, {len(rhythm)} rhythm, {len(memory)} memory timbres")


if __name__ == "__main__":
    main()
