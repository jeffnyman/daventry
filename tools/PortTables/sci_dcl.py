"""Converts the Huffman trees of ScummVM's common/compression/dcl.cpp into DclTables.g.cs.

The C source builds each tree from BN(pos, left, right) and LN(pos, value) macros. This script
evaluates the same macros, so the generated arrays are bit for bit what the C compiler produces.

    python tools/PortTables/sci_dcl.py [path/to/scummvm] [path/to/daventry]
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCUMMVM = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2] / "scummvm"
DAVENTRY = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE.parents[1]

SOURCE = SCUMMVM / "common" / "compression" / "dcl.cpp"
OUTPUT = DAVENTRY / "src" / "Daventry.Sci" / "Resources" / "DclTables.g.cs"

HUFFMAN_LEAF = 0x40000000


def parse_tree(text, name):
    start = text.index(f"static const int {name}[] = {{")
    end = text.index("};", start)
    body = text[start:end]
    values = []
    for kind, args in re.findall(r"\b(BN|LN)\(([^)]*)\)", body):
        parts = [int(p) for p in args.split(",")]
        if kind == "BN":
            _, left, right = parts
            values.append((left << 12) | right)
        else:
            _, value = parts
            values.append(value | HUFFMAN_LEAF)
    return values


def emit(trees):
    lines = [
        "// <auto-generated>",
        "// Generated by tools/PortTables/sci_dcl.py from ScummVM's common/compression/dcl.cpp.",
        "// Do not edit by hand; rerun the script after updating the ScummVM checkout.",
        "// </auto-generated>",
        "",
        "namespace Daventry.Sci.Resources;",
        "",
        "internal static class DclTables",
        "{",
        "    public const int HuffmanLeaf = 0x40000000;",
        "",
    ]
    for name, values in trees:
        lines.append(f"    public static readonly int[] {name} =")
        lines.append("    [")
        for i in range(0, len(values), 8):
            chunk = ", ".join(f"0x{v:08X}" for v in values[i:i + 8])
            lines.append(f"        {chunk},")
        lines.append("    ];")
        lines.append("")
    lines[-1] = "}"
    lines.append("")
    return "\n".join(lines)


def main():
    text = SOURCE.read_text(encoding="utf-8")
    trees = [
        ("LengthTree", parse_tree(text, "length_tree")),
        ("DistanceTree", parse_tree(text, "distance_tree")),
        ("AsciiTree", parse_tree(text, "ascii_tree")),
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(emit(trees), encoding="utf-8", newline="\n")
    print("wrote", OUTPUT, [(n, len(v)) for n, v in trees])


if __name__ == "__main__":
    main()
